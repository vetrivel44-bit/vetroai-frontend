// GPT Image 2 through Puter (loaded by index.html): used for generated images
// in the chat and for the detailed version of a drawing (SketchBlock).

const blobToDataUrl = (blob) => new Promise((resolve, reject) => {
  const reader = new FileReader();
  reader.onload = () => resolve(reader.result);
  reader.onerror = () => reject(new Error("Could not read the image."));
  reader.readAsDataURL(blob);
});

export async function generateImageViaPuter(prompt) {
  await window.whenPuter?.();
  if (!window.puter?.ai?.txt2img) {
    throw new Error("GPT Image 2 could not load. Check your connection and refresh the page.");
  }
  const image = await window.puter.ai.txt2img(prompt, { model: "gpt-image-2" });
  const src = image?.src || image?.url;
  if (!src) throw new Error("GPT Image 2 returned an empty image.");
  // Puter can return a blob URL. ReactMarkdown sanitizes blob URLs and they also
  // expire after a reload, so persist the generated bytes as a data URL instead.
  if (src.startsWith("blob:")) {
    const response = await fetch(src);
    if (!response.ok) throw new Error("GPT Image 2 returned an unreadable image.");
    return blobToDataUrl(await response.blob());
  }
  return src;
}

// Asking to draw or sketch something, or for a drawing or diagram, is a
// drawing in the chat (a ```sketch, with a detailed version): only other
// image requests ("generate an image of…") go straight to the image model.
export const wantsDrawing = (text) => /\b(draw|drawing|sketch|diagram)\b/i.test(String(text || ""));
